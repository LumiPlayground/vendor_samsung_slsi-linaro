Return<void> RadioExternalImpl::sendRequestRawSegment(int32_t serial,
            int32_t clientId,
            int32_t rilcReqId,
            int32_t slotId,
            int32_t dataLen,
            const ::android::hardware::hidl_vec<uint8_t>& data,
            int32_t segIndex,
            int32_t totalLen){
#if VDBG
    RLOGD("%s: %d", __FUNCTION__, serial);
#endif
    RilExternalManager *mgr = RilExternalManager::getInstance();
    RequestRawSegmentData *buffer = mgr->allocateBuffer(serial, clientId, rilcReqId, slotId, totalLen);
    if (buffer != NULL) {
        const uint8_t *rawdata = data.data();
        size_t datalen = data.size();
        int ret = buffer->setToExternal(segIndex, rawdata, datalen);
        if (ret < 0) {
            RLOGD("sendRequestRawSegment: setToExternal error(%d). %s serial %d, clientId %d, slotId %d, segIndex %d, dataLen %d totalLen %d",
                    ret, rilcRequestToString(rilcReqId), serial, clientId,  slotId, segIndex, dataLen, totalLen);
        }

        if (RIL_EXTERN_VDBG) {
            RLOGD("sendRequestRawSegment: %s serial %d, clientId %d, slotId %d, segIndex %d, dataLen %d totalLen %d",
                    rilcRequestToString(rilcReqId), serial, clientId,  slotId, segIndex, dataLen, totalLen);
        }

        if (buffer->assembled()) {
            if (IS_DEBUGABLE()) {
                RLOGD("sendRequestRawSegment: dispatched %s serial %d, clientId %d, slotId %d, totalLen %d",
                    rilcRequestToString(rilcReqId), serial, clientId,  slotId, totalLen);
            }
            external_dispatchRaw(buffer);
            buffer->reset();
        }
        else {
            int lastIndex = (int)((totalLen + MAX_RADIO_DATA_SIZE - 1) /  MAX_RADIO_DATA_SIZE) - 1;
            if (segIndex == lastIndex) {
                RLOGE("Assemble failure: %s(%d) serial %d, clientId %d, slotId %d, dataLen %zu totalLen %zu %0X",
                    rilcRequestToString(rilcReqId), rilcReqId, serial, clientId,  slotId,
                    buffer->mLen, buffer->mTotalLen, buffer->mFlag);
                external_sendErrorResponse(serial, clientId, rilcReqId, slotId, RIL_E_INVALID_ARGUMENTS);
                buffer->reset();
            }
        }
    }
    else {
        RLOGE("Buffer allocation failure: %s serial %d, clientId %d, slotId %d, segIndex %d",
            rilcRequestToString(rilcReqId), serial, clientId,  slotId, segIndex);
        external_sendErrorResponse(serial, clientId, rilcReqId, slotId, RIL_E_INTERNAL_ERR);
    }
    return Void();
}

