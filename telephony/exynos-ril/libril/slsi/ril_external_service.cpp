bool IS_DEBUGABLE()
{
    static int isDebugable = -1;
    if (isDebugable < 0) {
        bool vdbg = (SystemProperty::GetInt("persist.vendor.config.vdbg", 0) != 0);
        std::string type = SystemProperty::Get("ro.vendor.build.type", "");
        bool debug = (TextUtils::Equals(type.c_str(), "eng") ||
                      TextUtils::Equals(type.c_str(), "userdebug"));
        isDebugable = (vdbg || debug) ? 1 : 0;
        RLOGD("IS_DEBUGABLE()=%d", isDebugable);
    }
    return (isDebugable > 0);
}

