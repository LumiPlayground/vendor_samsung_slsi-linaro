void LimitStringToMaxLength(int rilLogCat, const char *className, std::string &s, int maxLength) {
    int length = s.length();
    if (length > maxLength) {
        RilLogWarning(rilLogCat, "%s length %d is more than max length %d", className, length, maxLength);
        s.resize(maxLength);
    }
}

